/* =========================================================================
   editor.mjs — 本地写作服务（入口）

   实现在 server/admin.mjs，这里是开发模式的一层薄壳。保留这个命令是因为
   README 和使用习惯都认它：

     node tools/editor.mjs              → http://127.0.0.1:4322
     node tools/editor.mjs --port 5000

   为什么是薄壳而不是各留一份实现：写路径只该有一份代码。两份各自演化的
   "保存"逻辑迟早会在某次改动后不一致 —— 那正是这个仓库已经记过的教训。
   ========================================================================= */

/* 开发模式由这个入口强制打开（不鉴权、只绑回环、挂 /site/ 站点预览）。
   必须先把 --dev 放进 argv 再动态导入：ESM 的静态 import 会在本文件函数体
   之前求值，那时 argv 还没被改过。 */
if (!process.argv.includes("--dev")) process.argv.push("--dev");
await import("../server/admin.mjs");
