#!/usr/bin/env bash
# =========================================================================
# lib.sh — 部署脚本共享的小函数
#
# 被 bootstrap.sh 和 deploy.sh source，也被 deploy/scripts.test.mjs 直接测。
# 单独拆出来就是为了能被测到：里面的 envval 挡着一个很隐蔽的坑。
# =========================================================================

ENV_FILE="${ENV_FILE:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/.env}"

say()  { printf '\n\033[1m== %s\033[0m\n' "$*"; }
ok()   { printf '  \033[32m✓\033[0m %s\n' "$*"; }
warn() { printf '  \033[33m!\033[0m %s\n' "$*"; }
die()  { printf '\n\033[31m错误：%s\033[0m\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------- envval
#
# 从 .env 里按键取值。
#
# 为什么不直接 `source .env`：
#   后台口令哈希长这样：scrypt$32768$8$1$<salt>$<key>
#   shell 会把 $32768 展开成 $3 加 "2768"，$3 未定义就是空串 ——
#   哈希被悄悄改成 scrypt2768...，登录永远失败，而部署过程一路绿灯。
#   这是个只在"部署全绿但密码登不进去"时才暴露的坑，所以这里只做文本取值，
#   一个字都不交给 shell 求值。
#
# 顺带处理三件小事：
#   · 去掉值两端多余的空白 —— 行尾多一个空格，SITE_DOMAIN 就带上了它，
#     表现是 ACME 签发莫名其妙地失败，而报错完全指不到这里
#   · 去掉两端的引号（docker compose 会自己剥，shell 这边也得能读）
#   · 去掉行尾的 \r（在 Windows 上编辑过 .env 很容易带上，同样是不可见字符）
#
# 顺序有讲究：先去空白再去引号。反过来的话，`"值" ` 这种（引号后还有个空格）
# 会因为结尾不是引号而剥不掉。
envval() {
  [ -f "$ENV_FILE" ] || return 0
  sed -n "s/^[[:space:]]*$1[[:space:]]*=[[:space:]]*//p" "$ENV_FILE" \
    | head -1 \
    | tr -d '\r' \
    | sed -e 's/[[:space:]]*$//' \
          -e 's/^"\(.*\)"$/\1/' \
          -e "s/^'\(.*\)'\$/\1/"
}
